#!/usr/bin/env python3
import json
import os
import sys
import time
from datetime import datetime, timezone

from google import genai
from google.genai import types

INPUT_FILE = "network_data.json"
OUTPUT_FILE = "docs/network-topology.md"
REQUEST_TIMEOUT_MS = 60_000

# Tried in order: if one model is overloaded or retired, the next one is used.
MODELS = [
    "gemini-3.8-flash",
    "gemini-flash-latest",
    "gemini-3.5-flash",
    "gemini-2.5-flash",
]


def build_prompt(data):
    return f"""You are a network documentation assistant. Using ONLY the JSON data below,
write a Markdown document with exactly these three sections:

## Network Topology
A short prose summary of the local devices and the Tailscale nodes.

## Diagram
A Mermaid `graph TD` diagram with one subgraph for the local network and one for the Tailscale network.

## Current Status
A list of devices or nodes that are offline or whose status is unknown. If everything is online, say so.

Rules:
- Do NOT invent devices, IP addresses, hostnames, or roles that are not in the data.
- If a status is "unknown", write "unknown"; never guess.
- Output valid Markdown only, with no extra commentary and no surrounding code fence.

DATA:
{json.dumps(data, indent=2, ensure_ascii=False)}
"""


def generate_documentation(prompt, max_retries_per_model=2):
    api_key = os.environ.get("GEMINI_API_KEY")
    if not api_key:
        sys.exit("[error] GEMINI_API_KEY environment variable is not set.")
    client = genai.Client(
        api_key=api_key,
        http_options=types.HttpOptions(timeout=REQUEST_TIMEOUT_MS),
    )

    last_error = None
    for model in MODELS:
        for attempt in range(1, max_retries_per_model + 1):
            print(f"Trying model '{model}' (attempt {attempt}/{max_retries_per_model})...")
            try:
                response = client.models.generate_content(model=model, contents=prompt)
                if response.text:
                    print(f"Success with model '{model}'.")
                    return response.text, model
                raise RuntimeError("empty response")
            except Exception as e:
                last_error = e
                print(f"[warn] '{model}' failed (attempt {attempt}): {str(e)[:150]}")
                if attempt < max_retries_per_model:
                    time.sleep(10 * attempt)
    sys.exit(f"[error] All models failed. Last error: {last_error}")


def save_documentation(text, model_used):
    text = text.strip()
    if text.startswith("```"):
        text = text.split("\n", 1)[1] if "\n" in text else ""
        text = text.rsplit("```", 1)[0].strip()
    header = (
        f"<!-- Auto-generated by generate_docs.py on "
        f"{datetime.now(timezone.utc).isoformat()} using model '{model_used}'. "
        f"Review against network_data.json before trusting this content "
        f"(see README: Responsible AI practices). -->\n\n"
    )
    os.makedirs(os.path.dirname(OUTPUT_FILE), exist_ok=True)
    with open(OUTPUT_FILE, "w") as f:
        f.write(header + text + "\n")
    print(f"Documentation saved to {OUTPUT_FILE} (model used: {model_used})")
    print("IMPORTANT: review the file against network_data.json before committing.")


def main():
    try:
        with open(INPUT_FILE) as f:
            data = json.load(f)
    except FileNotFoundError:
        sys.exit(f"[error] {INPUT_FILE} not found. Run collect_data.py first.")
    text, model_used = generate_documentation(build_prompt(data))
    save_documentation(text, model_used)


if __name__ == "__main__":
    main()